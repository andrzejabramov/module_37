// Размер поля
const size = 3;

// Проходим по строкам
for (let i = 0; i < size; i++) {
    let row = '';

    // Проходим по столбцам
    for (let j = 0; j < size; j++) {
        // Определяем, что ставить: x или o
        // Сумма индексов i + j чётная → x, нечётная → o
        if ((i + j) % 2 === 0) {
            row += 'x ';
        } else {
            row += 'o ';
        }
    }

    // Убираем лишний пробел в конце и выводим строку
    console.log(row.trim());
}